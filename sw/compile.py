#!/usr/bin/env python3
"""Step 3: compile the quantized network into a register program for the RTL.

  python3 sw/compile.py [--batch 8] [--nbatches N] [--rows 4] ...

Inputs : build/qnet.npz  (from sw/quantize.py)
Outputs: build/prog.hex       register program replayed by tb/tb_dnn_player.v
         build/prog_meta.json what each READ in the program means (for report.py)
         build/net_image.h    the same network as C arrays for driver/example
"""
import argparse
import json
import os
import sys
import numpy as np

sys.path.insert(0, os.path.dirname(__file__))
from dnn_cfg import HwCfg
import compiler_lib as cl

BUILD = os.path.join(os.path.dirname(__file__), "..", "build")


def load_qnet(path):
    z = np.load(path)
    layers = []
    for i in range(int(z["n_layers"])):
        layers.append(dict(w_q=z[f"L{i}_w_q"], bias_q=z[f"L{i}_bias_q"],
                           mult=int(z[f"L{i}_mult"]), shift=int(z[f"L{i}_shift"]),
                           relu=bool(z[f"L{i}_relu"])))
    return layers, z["x_q_test"], z["y_test"]


def emit_c_header(P, cfg, x_q, expected, path):
    """Network as C arrays: the C driver tiles/packs it itself."""
    def arr(name, a, ctype):
        flat = ", ".join(str(int(v)) for v in np.asarray(a).ravel())
        return f"static const {ctype} {name}[{np.asarray(a).size}] = {{{flat}}};\n"
    s = ["/* Generated by sw/compile.py - do not edit. */\n#pragma once\n#include <stdint.h>\n"
         "#include \"dnn_accel.h\"\n\n",
         f"#define NET_LAYERS {len(P)}\n#define NET_BATCH {x_q.shape[0]}\n"
         f"#define NET_HW_ROWS {cfg.rows}\n#define NET_HW_M_MAX {cfg.m_max}\n"
         f"#define NET_HW_KT_MAX {cfg.kt_max}\n#define NET_HW_NT_MAX {cfg.nt_max}\n"
         f"#define NET_HW_LAYERS {cfg.num_layers}\n#define NET_HW_ACT {cfg.act_depth}\n"
         f"#define NET_HW_WGT {cfg.wgt_depth}\n#define NET_HW_BIAS {cfg.bias_depth}\n"
         f"#define NET_HW_ACC {cfg.acc_depth}\n#define NET_HW_LRB {cfg.lrb_depth}\n\n"]
    for i, L in enumerate(P):
        s.append(f"/* layer {i}: K={L['K']}->{L['Kp']} N={L['N']}->{L['Np']} relu={int(L['relu'])} */\n")
        s.append(arr(f"L{i}_W", L["w_q"], "int8_t"))          # [Kp][Np] row-major
        s.append(arr(f"L{i}_B", L["bias_q"], "int32_t"))
    s.append("\nstatic const dnn_layer_t NET[NET_LAYERS] = {\n")
    for i, L in enumerate(P):
        s.append(f"  {{{L['Kp']}, {L['Np']}, {int(L['relu'])}, {L['mult']}u, {L['shift']}u, L{i}_W, L{i}_B}},\n")
    s.append("};\n\n")
    s.append(arr("NET_X", np.pad(x_q, ((0, 0), (0, P[0]["Kp"] - x_q.shape[1]))), "int8_t"))
    s.append(arr("NET_Y", expected[-1], "int8_t"))            # [batch][Np_last]
    with open(path, "w") as f:
        f.writelines(s)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--qnet", default=os.path.join(BUILD, "qnet.npz"))
    ap.add_argument("--out", default=BUILD)
    ap.add_argument("--batch", type=int, default=8)
    ap.add_argument("--nbatches", type=int, default=0, help="0 = whole test set")
    ap.add_argument("--rows", type=int, default=4)
    for k in ("act_depth", "wgt_depth", "bias_depth", "acc_depth", "lrb_depth",
              "num_layers", "m_max", "kt_max", "nt_max"):
        ap.add_argument("--" + k.replace("_", "-"), type=int, default=getattr(HwCfg, k))
    a = ap.parse_args()
    cfg = HwCfg(rows=a.rows, act_depth=a.act_depth, wgt_depth=a.wgt_depth,
                bias_depth=a.bias_depth, acc_depth=a.acc_depth, lrb_depth=a.lrb_depth,
                num_layers=a.num_layers, m_max=a.m_max, kt_max=a.kt_max, nt_max=a.nt_max)

    layers, x_all, y_all = load_qnet(a.qnet)
    P = cl.plan(layers, cfg, a.batch)
    nb = a.nbatches or len(x_all) // a.batch
    ops, reads = cl.probe_ops(cfg) + cl.static_ops(P, cfg), []
    n_static = len(ops)
    n_first = n_static
    for b in range(nb):
        xb = x_all[b * a.batch:(b + 1) * a.batch]
        exp = cl.expected_outputs(P, xb)
        ops += cl.input_ops(P, cfg, xb) + cl.run_ops()
        ops += cl.perf_ops(reads, b)
        ops += cl.readback_ops(P, cfg, exp[-1], reads, b)
        if b == 0:
            os.makedirs(a.out, exist_ok=True)
            emit_c_header(P, cfg, xb, exp, os.path.join(a.out, "net_image.h"))
            n_first = len(ops)

    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, "prog.hex"), "w") as f:
        f.write("\n".join(cl.to_hex_lines(ops)) + "\n")
    # the static part alone (weights/bias/descriptors) - used by the C-driver diff check
    with open(os.path.join(a.out, "prog_static.hex"), "w") as f:
        f.write("\n".join(cl.to_hex_lines(ops[:n_static])[:-1]) + "\n")
    meta = dict(cfg=cfg.__dict__, batch=a.batch, nbatches=nb, n_ops=len(ops),
                n_static_ops=n_static, n_first=n_first, reads=reads,
                labels=[int(v) for v in y_all[:nb * a.batch]],
                last_layer_n=int(P[-1]["N"]), last_layer_np=int(P[-1]["Np"]),
                nt_last=int(P[-1]["NT"]), rows=cfg.rows,
                macs_per_batch=int(sum(L["M"] * L["Kp"] * L["Np"] for L in P)),
                layers=[{k: int(L[k]) for k in ("K", "N", "Kp", "Np", "KT", "NT", "wbase", "bbase", "src", "dst")}
                        for L in P])
    with open(os.path.join(a.out, "prog_meta.json"), "w") as f:
        json.dump(meta, f)
    print(f"compiled {len(P)} layers, {nb} batches of {a.batch}: {len(ops)} register ops "
          f"({n_static} static), weight words {sum(L['KT']*L['NT']*cfg.rows for L in P)}/"
          f"{cfg.wgt_depth}")
    for i, L in enumerate(P):
        print(f"  layer {i}: K {L['K']}->{L['Kp']} (KT={L['KT']})  N {L['N']}->{L['Np']} (NT={L['NT']})  "
              f"passes={L['KT']*L['NT']}  src={L['src']} dst={L['dst']}  wbase={L['wbase']}")


if __name__ == "__main__":
    main()
